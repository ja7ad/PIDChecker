//! Versioned pkeyconfig catalog and its sync from the published `data/` folder.
//!
//! `data/manifest.toml` holds a catalog `version` and the SHA-256 of every data
//! file. When the published manifest has a higher version, the files whose hash
//! differs from the local copy are downloaded, verified, moved into place, and
//! the running checker swaps in a freshly loaded database: no restart needed.

use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::time::Duration;

use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use super::checker::Checker;
use crate::config::CatalogConfig;

pub const MANIFEST: &str = "manifest.toml";
/// Downloads are staged here (inside the data dir, so moves are atomic renames).
const STAGING: &str = ".sync";

#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct Manifest {
    #[serde(default)]
    pub version: u32,
    #[serde(default, rename = "file")]
    pub files: Vec<ManifestFile>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct ManifestFile {
    /// Path relative to the data directory, `/`-separated.
    pub path: String,
    pub sha256: String,
    pub size: u64,
}

impl Manifest {
    /// The local manifest, if present and readable.
    pub fn read(dir: &Path) -> Option<Self> {
        toml::from_str(&std::fs::read_to_string(dir.join(MANIFEST)).ok()?).ok()
    }

    /// Hash every data file currently in `dir` (version 0).
    pub fn scan(dir: &Path) -> Result<Self> {
        let mut paths = Vec::new();
        collect(dir, dir, &mut paths)?;
        paths.sort();
        let files = paths
            .into_iter()
            .map(|rel| {
                let full = dir.join(&rel);
                Ok(ManifestFile { sha256: sha256_file(&full)?, size: std::fs::metadata(&full)?.len(), path: rel })
            })
            .collect::<Result<_>>()?;
        Ok(Self { version: 0, files })
    }

    pub fn write(&self, dir: &Path) -> Result<()> {
        let text = format!(
            "# Generated by `pkc catalog manifest`; bump happens automatically when files change.\n\n{}",
            toml::to_string_pretty(self)?
        );
        let tmp = dir.join(format!("{MANIFEST}.tmp"));
        std::fs::write(&tmp, text).with_context(|| format!("writing {}", tmp.display()))?;
        std::fs::rename(&tmp, dir.join(MANIFEST)).context("replacing manifest")
    }
}

/// Regenerate `manifest.toml` from the files in `dir`, bumping the version
/// when anything changed. Returns the manifest and whether it changed.
pub fn update_manifest(dir: &Path) -> Result<(Manifest, bool)> {
    let old = Manifest::read(dir).unwrap_or_default();
    let mut new = Manifest::scan(dir)?;
    new.version = old.version;
    let changed = new.files != old.files;
    if changed {
        new.version += 1;
        new.write(dir)?;
    }
    Ok((new, changed))
}

/// Files that belong to the catalog: `catalog.toml` and the pkeyconfigs.
fn is_data_file(rel: &str) -> bool {
    let lower = rel.to_ascii_lowercase();
    lower == "catalog.toml" || lower.ends_with(".xrm-ms") || lower.ends_with(".xml")
}

/// A remote path must stay inside the data directory.
fn is_safe_path(rel: &str) -> bool {
    !rel.is_empty()
        && !rel.contains(['\\', ':'])
        && rel.split('/').all(|c| !c.is_empty() && c != "." && c != ".." && !c.starts_with('.'))
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) -> Result<()> {
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        let rel = path.strip_prefix(root).unwrap_or(&path).to_string_lossy().replace('\\', "/");
        if path.is_dir() {
            if !rel.starts_with('.') {
                collect(root, &path, out)?;
            }
        } else if is_data_file(&rel) {
            out.push(rel);
        }
    }
    Ok(())
}

pub fn sha256_file(path: &Path) -> Result<String> {
    let bytes = std::fs::read(path).with_context(|| format!("reading {}", path.display()))?;
    Ok(hex::encode(Sha256::digest(&bytes)))
}

#[derive(Debug, Clone, Serialize)]
pub struct SyncReport {
    pub from: u32,
    pub to: u32,
    pub updated: Vec<String>,
    pub removed: Vec<String>,
}

impl SyncReport {
    pub fn summary(&self) -> String {
        format!(
            "Catalog updated v{} → v{}: {} file(s) updated, {} removed",
            self.from,
            self.to,
            self.updated.len(),
            self.removed.len()
        )
    }
}

/// Only one sync at a time (startup, timer and "sync now" may overlap).
static SYNC_LOCK: tokio::sync::Mutex<()> = tokio::sync::Mutex::const_new(());

/// Bring `dir` up to the catalog published at `url`. `None` when already current.
pub async fn sync(dir: &Path, url: &str) -> Result<Option<SyncReport>> {
    let _guard = SYNC_LOCK.lock().await;
    let url = url.trim_end_matches('/');
    let http = reqwest::Client::builder()
        .timeout(Duration::from_secs(120))
        .user_agent(concat!("PIDKeyChecker/", env!("CARGO_PKG_VERSION")))
        .build()?;
    let get = async |rel: &str| -> Result<Vec<u8>> {
        let resp = http.get(format!("{url}/{rel}")).send().await?.error_for_status()?;
        Ok(resp.bytes().await?.to_vec())
    };

    let remote: Manifest = toml::from_str(&String::from_utf8_lossy(&get(MANIFEST).await.context("fetching manifest")?))
        .context("parsing remote manifest")?;
    let local = Manifest::read(dir).unwrap_or_default();
    if remote.version <= local.version {
        return Ok(None);
    }
    if let Some(f) = remote.files.iter().find(|f| !is_safe_path(&f.path) || !is_data_file(&f.path)) {
        bail!("remote manifest lists an unexpected path: {}", f.path);
    }

    // Compare against the files on disk, not the local manifest: it may be
    // missing or stale after a manual edit.
    let changed: Vec<ManifestFile> = {
        let (dir, files) = (dir.to_path_buf(), remote.files.clone());
        tokio::task::spawn_blocking(move || {
            files.into_iter().filter(|f| sha256_file(&dir.join(&f.path)).ok().as_deref() != Some(&f.sha256)).collect()
        })
        .await?
    };

    let staging = dir.join(STAGING);
    let _ = std::fs::remove_dir_all(&staging);
    std::fs::create_dir_all(&staging).with_context(|| format!("creating {}", staging.display()))?;
    let result = async {
        let mut staged: Vec<(PathBuf, &ManifestFile)> = Vec::new();
        for (i, f) in changed.iter().enumerate() {
            let bytes = get(&f.path).await.with_context(|| format!("downloading {}", f.path))?;
            if bytes.len() as u64 != f.size || hex::encode(Sha256::digest(&bytes)) != f.sha256 {
                bail!("{} does not match the manifest checksum", f.path);
            }
            let tmp = staging.join(i.to_string());
            std::fs::write(&tmp, bytes)?;
            staged.push((tmp, f));
        }
        // Everything verified: move into place.
        for (tmp, f) in &staged {
            let dest = dir.join(&f.path);
            if let Some(parent) = dest.parent() {
                std::fs::create_dir_all(parent)?;
            }
            std::fs::rename(tmp, &dest).with_context(|| format!("replacing {}", dest.display()))?;
        }
        // Drop files the previous catalog shipped and the new one no longer lists.
        let mut removed = Vec::new();
        for f in &local.files {
            if is_safe_path(&f.path)
                && !remote.files.iter().any(|r| r.path == f.path)
                && std::fs::remove_file(dir.join(&f.path)).is_ok()
            {
                removed.push(f.path.clone());
            }
        }
        remote.write(dir)?;
        Ok(SyncReport {
            from: local.version,
            to: remote.version,
            updated: changed.iter().map(|f| f.path.clone()).collect(),
            removed,
        })
    }
    .await;
    let _ = std::fs::remove_dir_all(&staging);
    result.map(Some)
}

/// Sync the checker's data directory and, if anything changed, reload its database.
pub async fn sync_and_reload(checker: &Arc<Checker>, url: &str) -> Result<Option<SyncReport>> {
    let Some(report) = sync(checker.data_dir(), url).await? else { return Ok(None) };
    let c = checker.clone();
    tokio::task::spawn_blocking(move || c.reload()).await??;
    tracing::info!("{}", report.summary());
    Ok(Some(report))
}

/// Check for catalog updates now and then every `interval_hours`, in the background.
pub fn spawn_auto_sync(checker: Arc<Checker>, cfg: &CatalogConfig) -> Option<tokio::task::JoinHandle<()>> {
    if !cfg.auto_sync {
        return None;
    }
    let (url, every) = (cfg.url.clone(), cfg.interval());
    Some(tokio::spawn(async move {
        loop {
            if let Err(e) = sync_and_reload(&checker, &url).await {
                tracing::warn!("catalog sync failed: {e:#}");
            }
            tokio::time::sleep(every).await;
        }
    }))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_paths_outside_data_dir() {
        assert!(is_safe_path("office/2024/pkeyconfig.xrm-ms"));
        assert!(is_safe_path("catalog.toml"));
        for bad in ["../x.xrm-ms", "/etc/x.xml", "a//b.xml", "C:/x.xml", "a\\b.xml", ".sync/x.xml", "a/./b.xml", ""] {
            assert!(!is_safe_path(bad), "{bad}");
        }
        assert!(!is_data_file("config.toml"));
    }

    #[test]
    fn manifest_bumps_only_on_change() {
        let dir = std::env::temp_dir().join(format!("pkc-catalog-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir_all(dir.join("office/2024")).unwrap();
        std::fs::write(dir.join("catalog.toml"), "").unwrap();
        std::fs::write(dir.join("office/2024/pkeyconfig.xrm-ms"), "a").unwrap();
        let (m, changed) = update_manifest(&dir).unwrap();
        assert!(changed);
        assert_eq!(m.version, 1);
        assert_eq!(m.files.len(), 2);
        assert!(!update_manifest(&dir).unwrap().1);
        std::fs::write(dir.join("office/2024/pkeyconfig.xrm-ms"), "b").unwrap();
        assert_eq!(update_manifest(&dir).unwrap().0.version, 2);
        assert_eq!(Manifest::read(&dir).unwrap().version, 2);
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
